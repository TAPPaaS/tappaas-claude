#!/usr/bin/env bash
# mac-devenv.sh — a local test environment on the Mac that matches what the
# TAPPaaS test suites see on a mothership (nixos-26.05 pin):
#   node 22, TypeScript 5.9.3, Python 3.13 (+ httpx, jsonschema, pytest, ...),
#   bash 5, GNU coreutils/sed/grep/find/tar/awk, jq, shellcheck, bats,
#   postgresql 16 (cmdb-controller suite).
#
# Nothing global changes: the tools live in Homebrew kegs and ~/.tappaas/devenv,
# and only shells that source ~/.tappaas/devenv/env.sh see them (direnv in
# ~/src/TAPPaaS*, the tappaas-env wrapper, the Claude Code SessionStart hook).
#
#   scripts/mac-devenv.sh          install/refresh the toolchain (idempotent)
#   scripts/mac-devenv.sh --hooks  ...and add .envrc to ~/src/TAPPaaS* + direnv hook in ~/.zshrc
#   scripts/mac-devenv.sh --check  report versions only
set -euo pipefail

DEV="${HOME}/.tappaas/devenv"
TS_VERSION="5.9.3"          # nixpkgs nixos-26.05: pkgs/by-name/ty/typescript
PY="python@3.13"            # nixos-26.05: python3 = python313
NODE="node@22"              # test scripts use nodejs_22
PG="postgresql@16"          # cmdb-controller test: postgresql_16
BREW_PKGS=(bash "$NODE" "$PY" "$PG" coreutils gnu-sed findutils grep gnu-tar gawk
           jq shellcheck bats-core direnv)
PY_PKGS=(httpx oxl-opnsense-client jsonschema pytest requests)

BREW=/opt/homebrew/bin/brew
[[ -x "$BREW" ]] || { echo "Homebrew not found at $BREW" >&2; exit 1; }
OPT="$("$BREW" --prefix)/opt"

check() {
    # shellcheck disable=SC1091
    . "${DEV}/env.sh"
    printf '%-11s %s\n' bash "$(bash --version | head -1 | awk '{print $4}')" \
        node "$(node --version)" tsc "$(tsc --version | awk '{print $2}')" \
        python3 "$(python3 --version | awk '{print $2}')" \
        timeout "$(command -v timeout)" sed "$(sed --version | head -1)" \
        stat "$(stat --version | head -1)" jq "$(jq --version)" \
        shellcheck "$(shellcheck --version | awk '/^version/{print $2}')" \
        postgres "$(postgres --version | awk '{print $3}')"
    python3 -c 'import httpx, jsonschema, oxl_opnsense_client, pytest' && echo "python deps ok"
}
if [[ "${1:-}" == "--check" ]]; then check; exit 0; fi

echo "== Homebrew packages"
"$BREW" install --quiet "${BREW_PKGS[@]}"

mkdir -p "$DEV"

echo "== TypeScript ${TS_VERSION} (in ${DEV}, run with ${NODE})"
cat > "${DEV}/package.json" <<EOF
{ "private": true, "description": "TAPPaaS Mac test toolchain (scripts/mac-devenv.sh)",
  "devDependencies": { "typescript": "${TS_VERSION}" } }
EOF
(cd "$DEV" && PATH="${OPT}/${NODE}/bin:$PATH" npm install --no-audit --no-fund --silent)

echo "== Python venv (${PY})"
if [[ ! -x "${DEV}/venv/bin/python3" ]] || \
   ! "${DEV}/venv/bin/python3" -c 'import sys; sys.exit(sys.version_info[:2] != (3, 13))'; then
    rm -rf "${DEV}/venv"
    "${OPT}/${PY}/bin/python3.13" -m venv "${DEV}/venv"
fi
"${DEV}/venv/bin/pip" install --quiet --upgrade pip "${PY_PKGS[@]}"

echo "== ${DEV}/env.sh"
cat > "${DEV}/env.sh" <<EOF
# Generated by tappaas-claude/scripts/mac-devenv.sh — source it, do not edit.
# Prepends the TAPPaaS test toolchain; safe to source more than once.
if [ -z "\${TAPPAAS_DEVENV:-}" ]; then
    export TAPPAAS_DEVENV="${DEV}"
    # Built back to front; the result is, first to last: tsc 5.9.3, the 3.13
    # venv, node 22, GNU tools, /opt/homebrew/bin (bash 5 over /bin/bash 3.2),
    # postgres 16, then the caller's PATH.
    PATH="${OPT}/${PG}/bin:\$PATH"
    PATH="/opt/homebrew/bin:\$PATH"
    for _g in gawk gnu-tar grep findutils gnu-sed coreutils; do
        [ -d "${OPT}/\${_g}/libexec/gnubin" ] && PATH="${OPT}/\${_g}/libexec/gnubin:\$PATH"
    done
    PATH="${DEV}/node_modules/.bin:${DEV}/venv/bin:${OPT}/${NODE}/bin:\$PATH"
    unset _g; export PATH
fi
EOF

echo "== ~/bin/tappaas-env (run one command inside the env)"
mkdir -p "${HOME}/bin"
cat > "${HOME}/bin/tappaas-env" <<'EOF'
#!/bin/sh
# tappaas-env <cmd...> — run a command with the TAPPaaS Mac test toolchain.
. "$HOME/.tappaas/devenv/env.sh"
[ $# -gt 0 ] || set -- "${SHELL:-/bin/zsh}"
exec "$@"
EOF
chmod +x "${HOME}/bin/tappaas-env"

if [[ "${1:-}" != "--hooks" ]]; then
    echo; check
    echo; echo "Shell hooks not touched. For direnv in ~/src/TAPPaaS* and ~/.zshrc: $0 --hooks"
    exit 0
fi

echo "== direnv for ~/src/TAPPaaS*"
for repo in "${HOME}"/src/TAPPaaS*; do
    [[ -d "${repo}/.git" ]] || continue
    echo 'source_env_if_exists ~/.tappaas/devenv/env.sh' > "${repo}/.envrc"
    grep -qxF '.envrc' "${repo}/.git/info/exclude" 2>/dev/null || echo '.envrc' >> "${repo}/.git/info/exclude"
    direnv allow "$repo" 2>/dev/null || true
done
grep -q 'direnv hook zsh' "${HOME}/.zshrc" 2>/dev/null || \
    printf '\n# TAPPaaS test env per repo (scripts/mac-devenv.sh)\neval "$(direnv hook zsh)"\n' >> "${HOME}/.zshrc"

echo; check
