#!/usr/bin/env bash
# mac-devenv.sh — a local test environment on the Mac that matches what the
# TAPPaaS test suites see on a mothership (nixos-26.05 pin):
#   node 22, TypeScript 5.9.3, Python 3.13 (+ httpx, jsonschema, pytest, ...),
#   bash 5, GNU coreutils/sed/grep/find/tar/awk, jq, shellcheck, bats,
#   postgresql 16 (cmdb-controller suite).
#
# Nothing global changes: the tools live in Homebrew kegs and ~/.tappaas/devenv,
# and only shells inside a TAPPaaS checkout see them: activate.sh (zsh cd hook,
# Claude Code SessionStart hook) or the tappaas-env wrapper.
#
#   scripts/mac-devenv.sh          install/refresh the toolchain (idempotent)
#   scripts/mac-devenv.sh --hooks  ...and add the zsh cd hook to ~/.zshrc
#   scripts/mac-devenv.sh --check  report versions only
set -euo pipefail

DEV="${HOME}/.tappaas/devenv"
TS_VERSION="5.9.3"          # nixpkgs nixos-26.05: pkgs/by-name/ty/typescript
PY="python@3.13"            # nixos-26.05: python3 = python313
NODE="node@22"              # test scripts use nodejs_22
PG="postgresql@16"          # cmdb-controller test: postgresql_16
BREW_PKGS=(bash "$NODE" "$PY" "$PG" coreutils gnu-sed findutils grep gnu-tar gawk
           jq shellcheck bats-core)
PY_PKGS=(httpx oxl-opnsense-client jsonschema pytest requests)

BREW=/opt/homebrew/bin/brew
[[ -x "$BREW" ]] || { echo "Homebrew not found at $BREW" >&2; exit 1; }
OPT="$("$BREW" --prefix)/opt"

check() {
    # shellcheck disable=SC1091
    . "${DEV}/env.sh"
    printf '%-11s %s\n' bash "$(bash --version | head -1 | awk '{print $4}')" \
        node "$(node --version)" tsc "$(tsc --version | awk '{print $2}')" \
        python3 "$(python3 --version | awk '{print $2}')" \
        timeout "$(command -v timeout)" sed "$(sed --version | head -1)" \
        stat "$(stat --version | head -1)" jq "$(jq --version)" \
        shellcheck "$(shellcheck --version | awk '/^version/{print $2}')" \
        postgres "$(postgres --version | awk '{print $3}')"
    python3 -c 'import httpx, jsonschema, oxl_opnsense_client, pytest' && echo "python deps ok"
}
if [[ "${1:-}" == "--check" ]]; then check; exit 0; fi

echo "== Homebrew packages"
"$BREW" install --quiet "${BREW_PKGS[@]}"

mkdir -p "$DEV"

echo "== TypeScript ${TS_VERSION} (in ${DEV}, run with ${NODE})"
cat > "${DEV}/package.json" <<EOF
{ "private": true, "description": "TAPPaaS Mac test toolchain (scripts/mac-devenv.sh)",
  "devDependencies": { "typescript": "${TS_VERSION}" } }
EOF
(cd "$DEV" && PATH="${OPT}/${NODE}/bin:$PATH" npm install --no-audit --no-fund --silent)

echo "== Python venv (${PY})"
if [[ ! -x "${DEV}/venv/bin/python3" ]] || \
   ! "${DEV}/venv/bin/python3" -c 'import sys; sys.exit(sys.version_info[:2] != (3, 13))'; then
    rm -rf "${DEV}/venv"
    "${OPT}/${PY}/bin/python3.13" -m venv "${DEV}/venv"
fi
"${DEV}/venv/bin/pip" install --quiet --upgrade pip "${PY_PKGS[@]}"

echo "== ${DEV}/env.sh"
cat > "${DEV}/env.sh" <<EOF
# Generated by tappaas-claude/scripts/mac-devenv.sh — source it, do not edit.
# Prepends the TAPPaaS test toolchain; safe to source more than once.
if [ -z "\${TAPPAAS_DEVENV:-}" ]; then
    export TAPPAAS_DEVENV="${DEV}"
    # Built back to front; the result is, first to last: tsc 5.9.3, the 3.13
    # venv, node 22, GNU tools, /opt/homebrew/bin (bash 5 over /bin/bash 3.2),
    # postgres 16, then the caller's PATH.
    PATH="${OPT}/${PG}/bin:\$PATH"
    PATH="/opt/homebrew/bin:\$PATH"
    for _g in gawk gnu-tar grep findutils gnu-sed coreutils; do
        [ -d "${OPT}/\${_g}/libexec/gnubin" ] && PATH="${OPT}/\${_g}/libexec/gnubin:\$PATH"
    done
    PATH="${DEV}/node_modules/.bin:${DEV}/venv/bin:${OPT}/${NODE}/bin:\$PATH"
    unset _g; export PATH
    # macOS TMPDIR is /var/folders/... and /var -> /private/var; bash's \$PWD
    # resolves it, os.tmpdir() does not, so tests comparing the two fail here
    # and pass on Linux. Hand everything the resolved path, as on a mothership.
    TMPDIR="\$(/bin/realpath "\${TMPDIR:-/tmp}")/"; export TMPDIR
    # An empty LANG/LC_ALL (the Claude app's shells) makes postgres refuse to
    # start on macOS ("postmaster became multithreaded"). C.UTF-8 keeps C's
    # byte-order collation and adds UTF-8.
    [ -n "\${LC_ALL:-}" ] || export LC_ALL=C.UTF-8
    [ -n "\${LANG:-}" ] || export LANG=C.UTF-8
fi
EOF

echo "== ${DEV}/activate.sh (switch the env on/off by the current directory)"
cat > "${DEV}/activate.sh" <<'EOF'
# Generated by tappaas-claude/scripts/mac-devenv.sh — source it, do not edit.
# Defines tappaas_env_sync and runs it once. Inside a TAPPaaS checkout (any
# worktree) it turns the toolchain on and points TAPPAAS_BIN at that checkout's
# dev bin; outside, it restores the shell as it was. zsh calls it on every cd;
# Claude Code sources this file before each Bash command (SessionStart hook).
# TAPPAAS_ENV_REBUILD=1 rebuilds the dev bin on entering a checkout (interactive
# shells); otherwise an existing one is reused (per-command use stays cheap).
tappaas_env_sync() {
    _te_top="$(git rev-parse --show-toplevel 2>/dev/null)" || _te_top=""
    if [ -n "$_te_top" ] && [ -f "$_te_top/src/foundation/tappaas-cicd/lib/common-install-routines.sh" ]; then
        [ "$_te_top" = "${_TAPPAAS_TOP:-}" ] && { unset _te_top; return 0; }
        if [ -z "${_TAPPAAS_TOP:-}" ]; then          # entering: remember the shell as it was
            _TAPPAAS_SAVE_PATH="$PATH"; _TAPPAAS_SAVE_TMPDIR="${TMPDIR-}"
            _TAPPAAS_SAVE_LC_ALL="${LC_ALL-}"; _TAPPAAS_SAVE_LANG="${LANG-}"
        fi
        PATH="$_TAPPAAS_SAVE_PATH"; unset TAPPAAS_DEVENV TAPPAAS_BIN
        . "$HOME/.tappaas/devenv/env.sh"
        _te_phys="$(/bin/realpath "$_te_top")"
        _te_bin="$HOME/.tappaas/devenv/bin/$(basename "$_te_phys")-$(printf '%s' "$_te_phys" | shasum | cut -c1-8)"
        if [ "${TAPPAAS_ENV_REBUILD:-0}" = 1 ] || [ ! -d "$_te_bin" ]; then
            _te_bin="$("$HOME/src/tappaas-claude/scripts/tappaas-dev-bin.sh" "$_te_top")" || _te_bin=""
        fi
        if [ -n "$_te_bin" ]; then TAPPAAS_BIN="$_te_bin"; PATH="$_te_bin:$PATH"; export TAPPAAS_BIN; fi
        export PATH; _TAPPAAS_TOP="$_te_top"
    elif [ -n "${_TAPPAAS_TOP:-}" ]; then           # leaving: put everything back
        PATH="$_TAPPAAS_SAVE_PATH"; export PATH
        if [ -n "$_TAPPAAS_SAVE_TMPDIR" ]; then export TMPDIR="$_TAPPAAS_SAVE_TMPDIR"; else unset TMPDIR; fi
        if [ -n "$_TAPPAAS_SAVE_LC_ALL" ]; then export LC_ALL="$_TAPPAAS_SAVE_LC_ALL"; else unset LC_ALL; fi
        if [ -n "$_TAPPAAS_SAVE_LANG" ]; then export LANG="$_TAPPAAS_SAVE_LANG"; else unset LANG; fi
        unset TAPPAAS_DEVENV TAPPAAS_BIN _TAPPAAS_TOP _TAPPAAS_SAVE_PATH _TAPPAAS_SAVE_TMPDIR \
              _TAPPAAS_SAVE_LC_ALL _TAPPAAS_SAVE_LANG
    fi
    unset _te_top _te_phys _te_bin
}
tappaas_env_sync
EOF

echo "== ~/bin/tappaas-env (run one command inside the env)"
mkdir -p "${HOME}/bin"
cat > "${HOME}/bin/tappaas-env" <<'EOF'
#!/bin/sh
# tappaas-env <cmd...> — run a command with the TAPPaaS Mac test toolchain.
. "$HOME/.tappaas/devenv/env.sh"
# Inside a TAPPaaS checkout: a mothership-shaped bin of its scripts, first on PATH,
# and TAPPAAS_BIN pointing there (scripts source common-install-routines.sh from it).
if [ -z "${TAPPAAS_BIN:-}" ] && _top="$(git rev-parse --show-toplevel 2>/dev/null)" \
   && [ -f "${_top}/src/foundation/tappaas-cicd/lib/common-install-routines.sh" ] \
   && TAPPAAS_BIN="$("$HOME/src/tappaas-claude/scripts/tappaas-dev-bin.sh" "${_top}")"; then
    PATH="${TAPPAAS_BIN}:${PATH}"; export TAPPAAS_BIN PATH
fi
unset _top
[ $# -gt 0 ] || set -- "${SHELL:-/bin/zsh}"
exec "$@"
EOF
chmod +x "${HOME}/bin/tappaas-env"

if [[ "${1:-}" != "--hooks" ]]; then
    echo; check
    echo; echo "Shell hooks not touched. To switch the env on by directory (zsh cd hook): $0 --hooks"
    exit 0
fi

echo "== zsh: switch the env on/off on every cd (~/.zshrc)"
grep -q 'tappaas/devenv/activate.sh' "${HOME}/.zshrc" 2>/dev/null || cat >> "${HOME}/.zshrc" <<'EOF'

# TAPPaaS test toolchain inside TAPPaaS checkouts (tappaas-claude/scripts/mac-devenv.sh)
if [ -r "$HOME/.tappaas/devenv/activate.sh" ]; then
    TAPPAAS_ENV_REBUILD=1 . "$HOME/.tappaas/devenv/activate.sh"
    autoload -Uz add-zsh-hook
    _tappaas_chpwd() { TAPPAAS_ENV_REBUILD=1 tappaas_env_sync; }
    add-zsh-hook chpwd _tappaas_chpwd
fi
EOF
echo "   Claude Code: SessionStart hook in ~/.claude/settings.json sources activate.sh (set up separately)"

echo; check
